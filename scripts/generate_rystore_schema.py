"""Gera retail_analytics/src/retail_analytics/rystore_schema.py a partir do contrato contracts/rystore.odcs.yaml.

O esquema do código nunca é editado à mão: mude o contrato e rode o gerador. O teste
retail_analytics/tests/test_schema.py confere que o arquivo é igual ao que o gerador produz.

Uso, na raiz do repositório:
    uv run --with pyyaml python scripts/generate_rystore_schema.py           # escreve o arquivo
    uv run --with pyyaml python scripts/generate_rystore_schema.py --check   # só confere, sem escrever
"""

import argparse
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[1]
CONTRACT = ROOT / "contracts" / "rystore.odcs.yaml"
TARGET = ROOT / "retail_analytics" / "src" / "retail_analytics" / "rystore_schema.py"


def render(contract):
    """The text of rystore_schema.py for a parsed contract."""
    tables = sorted(contract["schema"], key=lambda t: t["name"])
    out = [f'"""The RYStore schema as agreed in contracts/rystore.odcs.yaml (v{contract["version"]}).',
           "",
           "Generated by scripts/generate_rystore_schema.py; do not edit by hand. tests/test_schema.py checks it.",
           '"""',
           "",
           f'CONTRACT_VERSION = "{contract["version"]}"',
           "",
           "# table -> columns in delivery order: (name, logical type, required)",
           "COLUMNS = {"]
    for t in tables:
        out.append(f'    "{t["name"]}": [')
        out += [f'        ("{p["name"]}", "{p["logicalType"]}", {p["required"]}),' for p in t["properties"]]
        out.append("    ],")
    out += ["}", "", "PRIMARY_KEYS = {"]
    for t in tables:
        keys = sorted((p for p in t["properties"] if p.get("primaryKey")), key=lambda p: p["primaryKeyPosition"])
        out.append(f'    "{t["name"]}": {[p["name"] for p in keys]!r},')
    out += ["}", "", '# table -> [(column, "parent_table.parent_column")]', "FOREIGN_KEYS = {"]
    for t in tables:
        fks = [(p["name"], r["to"]) for p in t["properties"] for r in p.get("relationships") or [] if r.get("type") == "foreignKey"]
        if fks:
            out.append(f'    "{t["name"]}": {fks!r},')
    out += ["}", "", '# "changes": one file per day (incremental); "full": the whole table every day', "LOAD = {"]
    for t in tables:
        load = next(c["value"] for c in t.get("customProperties", []) if c["property"] == "load")
        out.append(f'    "{t["name"]}": "{load}",')
    out += ["}", "", "# (table, column) -> the closed list of values (contract: invalidValues with validValues; a new value is a warning)",
            "VALID_VALUES = {"]
    for t in tables:
        for p in t["properties"]:
            for q in p.get("quality") or []:
                values = (q.get("arguments") or {}).get("validValues")
                if values:
                    out.append(f"    ({t['name']!r}, {p['name']!r}): {values!r},")
    out += ["}", ""]
    return "\n".join(out)


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true", help="só confere se o arquivo está igual ao contrato")
    args = parser.parse_args()
    text = render(yaml.safe_load(CONTRACT.read_text(encoding="utf-8")))
    if args.check:
        same = TARGET.read_text(encoding="utf-8") == text
        print("rystore_schema.py igual ao contrato" if same else "rystore_schema.py diferente do contrato: rode o gerador")
        sys.exit(0 if same else 1)
    TARGET.write_text(text, encoding="utf-8")
    print(f"escrito {TARGET.relative_to(ROOT).as_posix()}")


if __name__ == "__main__":
    main()
